#pragma once
#include "matrix.h"
#include <iostream>

// ============================================================================
// Tensor 类 — 四维张量（Matrix 的 4D 语义薄封装）
// ============================================================================
//
// 【一句话概括】
// Tensor = Matrix + 形状标签。它不额外存储数据，只是给 2D 的 Matrix 加上
// (N, C, H, W) 的 4D 语义，让你可以用 4 个下标访问元素。
//
// 【为什么 CNN 需要 4D？】
// 卷积神经网络里的数据天然是 4 维的：
//   N (batch)  : 一批几张图？通常是 16、32、64。
//   C (channel): 每张图几个通道？灰度图=1，RGB=3，中间特征图=32/64/128...
//   H (height) : 图多高？输入通常是 64 像素。
//   W (width)  : 图多宽？输入通常是 64 像素。
//
// 【Tensor 和 Matrix 的关系——用类比理解】
// 可以把 Matrix 想象成一维数组 std::vector<double>，
// 把 Tensor 想象成给它加上了「行数、列数」标签的 Matrix。
//
//   原始数据:       std::vector<double>    — 一长串数字，不知道什么意思
//   Matrix 做的事:  加了 rows, cols        — 哦这是 2D 矩阵！
//   Tensor 做的事:  加了 N, C, H, W        — 哦这是 4D 张量！
//
// 每一层都是在下一层基础上加「形状语义」，不复制数据。
//
// 【数据在内存里的实际布局】
// Tensor 内部只持有一个 Matrix：
//   Matrix data;  // 形状是 (N, C*H*W)
//
// 每一行 = 一个样本的所有通道展平
// 行内排列 = CHW 顺序：先遍历通道，每个通道内遍历空间
//
// 举例：Tensor(N=2, C=3, H=4, W=5)
//   → 内部 Matrix(rows=2, cols=60)
//   → 第 0 行 = 样本 0 的 3×4×5=60 个像素值展平
//   → 第 1 行 = 样本 1 的 60 个像素值展平
//
// 4D 下标 → 2D 下标的换算：
//   at(n, c, h, w) → data.at(n,  c*H*W + h*W + w)
//                                  ↑              ↑
//                               跳到第c通道    通道内跳到(h,w)
//
// 【性能：零开销抽象】
// Tensor 的所有方法都非常短，编译器会直接把函数体嵌入调用处（内联），
// 不会产生额外的函数调用开销。Tensor 不分配额外内存，不复制数据。
// 它在运行时的成本 = 0。它的存在纯粹是为了让代码更清晰、更不容易写错。
// ============================================================================

class Tensor {
public:
    // 真正的数据存这里，形状是 (N, C*H*W)
    // public 是因为各层（Conv2D、ReLU 等）需要直接操作底层 Matrix
    Matrix data;

    // 4D 形状标签：批量大小、通道数、高度、宽度
    int N, C, H, W;

    // ------------------------------------------------------------------
    // 构造函数 1：指定 4D 形状 + 初始值
    //
    // 例子：
    //   Tensor t(16, 3, 64, 64);         // 16 张 3 通道 64×64 图片，初始全 0
    //   Tensor t(32, 1, 28, 28, 0.5);   // 32 张单通道 28×28，初始全 0.5
    // ------------------------------------------------------------------
    Tensor(int n, int c, int h, int w, double init_val = 0.0);

    // ------------------------------------------------------------------
    // 构造函数 2：用现成的 Matrix 来创建 Tensor（不复制数据，直接接管）
    //
    // 会检查 Matrix 的形状是否匹配 Tensor 的 4D 形状
    // 不匹配就抛异常（std::invalid_argument）
    //
    // 例子：
    //   Matrix m(4, 100);  // 4 个样本，每个 100 个特征
    //   Tensor t(m, 4, 1, 10, 10);  // 解读为 (N=4, C=1, H=10, W=10)
    // ------------------------------------------------------------------
    Tensor(const Matrix& m, int n, int c, int h, int w);

    // ------------------------------------------------------------------
    // 4D 元素访问 at(n, c, h, w)
    //
    // 参数：
    //   n — 第几个样本（batch index），0 到 N-1
    //   c — 第几个通道（channel index），0 到 C-1
    //   h — 第几行（height index），0 到 H-1
    //   w — 第几列（width index），0 到 W-1
    //
    // 内部换算：data.at(n, c*H*W + h*W + w)
    //   c*H*W   = 跳过前面 c 个通道的所有像素
    //   h*W + w = 当前通道内第 h 行第 w 列的偏移
    // ------------------------------------------------------------------
    double& at(int n, int c, int h, int w);
    const double& at(int n, int c, int h, int w) const;

    // ------------------------------------------------------------------
    // reshape — 换一个 4D 形状，元素总数必须一致
    //
    // 例子：
    //   Tensor t(2, 3, 4, 5);        // 共 120 个元素
    //   Tensor flat = t.reshape(1, 1, 1, 120);  // 展平成 1D
    //
    // CNN 里的典型用法：
    //   卷积层输出 (N, C, H, W) → reshape 成 (N, C*H*W) → 送入全连接层
    // ------------------------------------------------------------------
    Tensor reshape(int n, int c, int h, int w) const;

    // ------------------------------------------------------------------
    // 逐元素运算 — 全部委托给底层 Matrix，形状保持不变
    // ------------------------------------------------------------------
    Tensor operator+(const Tensor& other) const;
    Tensor operator-(const Tensor& other) const;
    Tensor operator*(double scalar) const;
    Tensor hadamard(const Tensor& other) const;  // 逐元素相乘
    Tensor& operator+=(const Tensor& other);
    Tensor& operator*=(double scalar);

    // ------------------------------------------------------------------
    // 批量修改元素值 — 委托给 Matrix
    // ------------------------------------------------------------------
    void fill(double val);              // 全部填成 val
    void randomize(double min, double max);  // 随机填充 [min, max]

    // ------------------------------------------------------------------
    // 形状查询
    // ------------------------------------------------------------------
    int total_elements() const { return N * C * H * W; }  // 元素总数
    int spatial_size()   const { return H * W; }          // 单通道的空间大小

    // ------------------------------------------------------------------
    // 打印 — 按 batch → channel → row 的层次结构输出
    //
    // 输出示例（单样本单通道 2×3）：
    //   Tensor(1,1,2,3)
    //   1 2 3
    //   4 5 6
    //
    // 多样本多通道会显示 batch N 和 channel C 标签
    // ------------------------------------------------------------------
    void print() const;

    // ------------------------------------------------------------------
    // 静态工厂方法 — 语法糖，让代码更可读
    // ------------------------------------------------------------------
    static Tensor zeros(int n, int c, int h, int w);
    static Tensor ones(int n, int c, int h, int w);
    static Tensor random(int n, int c, int h, int w, double min, double max);
};
